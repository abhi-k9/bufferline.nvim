describe("public pin query", function()
  it("queries live pin state without rendering or changing scope", function()
    local bufferline = require("bufferline")
    local groups = require("bufferline.groups")
    bufferline.setup()
    local current = vim.api.nvim_get_current_buf()
    local hidden = vim.api.nvim_create_buf(false, false)
    groups.add_element("pinned", { id = hidden })
    assert.is_true(bufferline.is_pinned(hidden))
    assert.is_true(groups.is_pinned(hidden))
    assert.is_false(vim.bo[hidden].buflisted)
    assert.equals(current, vim.api.nvim_get_current_buf())
    groups.remove_element("pinned", { id = hidden })
    assert.is_false(bufferline.is_pinned(hidden))
    groups.add_element("pinned", { id = current })
    assert.is_true(bufferline.is_pinned(0))
    groups.remove_element("pinned", { id = current })
    vim.api.nvim_buf_delete(hidden, { force = true })
    for _, invalid in ipairs({ hidden, -1, 0.5, "0", {}, math.huge }) do
      assert.is_false(bufferline.is_pinned(invalid))
    end
    assert.is_false(bufferline.is_pinned(nil))
  end)
end)
